"""Emit compiled capsule bindings; runtime reads no JSON and ships no game meshes."""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parents[1]

def number(value):
    assert math.isfinite(value)
    s = format(value, '.9g')
    if '.' not in s and 'e' not in s:
        s += '.0'
    return s + 'f'

def vec(values):
    return '{' + ', '.join(number(v) for v in values) + '}'

def endpoint(e):
    return '{' + json.dumps(e['bone'], ensure_ascii=True) + ', ' + vec(e['p']) + '}'

def generate_left():
    source = json.loads((ROOT / 'documents/left-weapon-collision-shapes.json').read_text(encoding='utf-8'))
    lines = ['// Generated by tools/generate_weapon_authored.py. Do not edit.',
             '#pragma once', '#include "core/vr/solid_weapon.h"', '#include <span>',
             'namespace VR::LeftClash {']
    cases = []
    for w in source['weapons']:
        family = int(w['id'].removeprefix('left:'))
        assert w['form'] == 'L' and w['coordinateFrame'] == 'stored-mesh-bind'
        assert 0 < len(w['capsules']) <= 7
        name = f'Caps_{family}'
        lines.append(f'inline constexpr Solid::Capsule {name}[] = {{')
        for c in w['capsules']:
            assert all(len(c[k]) == 3 and all(abs(x) < 10 for x in c[k]) for k in ('a', 'b'))
            assert .005 <= c['r'] <= .2
            lines.append('    {' + vec(c['a']) + ', ' + vec(c['b']) + ', ' + number(c['r']) + '},')
        lines.append('};')
        cases.append(f'    case {family}: return {name};')
    lines += ['inline std::span<const Solid::Capsule> Find(int family) {', '    switch (family) {',
              *cases, '    default: return {};', '    }', '}', '} // namespace VR::LeftClash', '']
    (ROOT / 'src/core/vr/left_clash_data.h').write_text('\n'.join(lines), encoding='utf-8')

def main():
    generate_left()
    draft = json.loads((ROOT / 'documents/weapon-collision-shapes.json').read_text(encoding='utf-8'))
    bindings = json.loads((ROOT / 'documents/weapon-collision-bindings.json').read_text(encoding='utf-8'))
    source = {w['id']: w for w in draft['weapons']}
    lines = ['// Generated by tools/generate_weapon_authored.py. Do not edit.',
             '#pragma once', '#include "core/vr/weapon_authored.h"',
             'namespace VR::WeaponAuthored {']
    names = []
    seen = set()
    for w in bindings['weapons']:
        assert w['id'] not in seen
        seen.add(w['id'])
        original = source[w['id']]
        assert w['sourceCapsules'] == original['capsules'], 'Rebind changed source endpoints before generating'
        assert (w['model'], w['form']) == (original['model'], original['form'])
        assert w.get('hand', 'right') == original.get('hand', 'right')
        assert 0 < len(w['capsules']) == len(original['capsules']) <= 7
        name = 'Caps_' + w['id'].replace(':', '_')
        lines.append(f'inline constexpr Capsule {name}[] = {{')
        for c, before in zip(w['capsules'], original['capsules']):
            assert c['r'] == before['r']
            lines.append('    {' + endpoint(c['a']) + ', ' + endpoint(c['b']) + ', ' + number(c['r']) + '},')
        lines.append('};')
        names.append((w, name))
    assert seen == set(source)
    lines.append('inline constexpr Shape Shapes[] = {')
    for w, name in names:
        hand = ', true' if w.get('hand') == 'left' else ''
        lines.append('    {' + f"{w['model']}, {'true' if w['form']=='B' else 'false'}, {w['part']}, {name}{hand}" + '},')
    lines += ['};', 'inline const Shape* Find(int model, bool form_b, bool left = false) {',
              '    for (const auto& s : Shapes)',
              '        if (s.model == model && s.form_b == form_b && s.left == left) return &s;',
              '    return nullptr;', '}', '} // namespace VR::WeaponAuthored', '']
    (ROOT / 'src/core/vr/weapon_authored_data.h').write_text('\n'.join(lines), encoding='utf-8')

if __name__ == '__main__':
    main()
