#!/usr/bin/env python3
"""Bake the approved iris to a bounded sRGB RGBA8 mip chain; no runtime image decoder.
Requires Pillow and numpy only when regenerating. Normal builds use the checked-in header.
"""
from pathlib import Path
import hashlib
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'scratchpad/kos-ritual-preview/serpent-iris-source.png'
HEADER = ROOT / 'src/video_core/renderer_vulkan/vr_kos_iris_data.h'
SIZE = 128

def bake():
    with Image.open(SOURCE) as image:
        srgb = np.asarray(image.convert('RGB'), dtype=np.float32) / 255.0
    linear = np.where(srgb <= .04045, srgb / 12.92, ((srgb + .055) / 1.055) ** 2.4)
    data = bytearray()
    levels = []
    n = SIZE
    while n:
        # Filter every level from the source in linear light, not encoded sRGB.
        level = np.stack([np.asarray(Image.fromarray(linear[:, :, c]).resize(
            (n, n), Image.Resampling.LANCZOS)) for c in range(3)], axis=-1)
        level = np.clip(level, 0, 1)
        encoded = np.where(level <= .0031308, level * 12.92, 1.055 * level ** (1 / 2.4) - .055)
        rgba = np.full((n, n, 4), 255, dtype=np.uint8)
        rgba[:, :, :3] = np.rint(np.clip(encoded, 0, 1) * 255).astype(np.uint8)
        levels.append((n, len(data)))
        data.extend(rgba.tobytes())
        n //= 2
    assert len(data) == 87380 and len(levels) == 8
    assert all(offset % 4 == 0 for _, offset in levels)
    lines = ['// Generated by tools/assets/build_kos_iris.py. Do not edit.',
             '// Source SHA256: ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
             '#pragma once', '#include <array>', '#include <cstdint>',
             'namespace Vulkan::KosIrisData {',
             'inline constexpr std::uint32_t Size = 128, Levels = 8;',
             'inline constexpr std::array<std::uint32_t, Levels> Offsets{' + ','.join(str(x[1]) for x in levels) + '};',
             'alignas(4) inline constexpr std::array<std::uint8_t, 87380> Pixels{']
    lines.extend('    ' + ','.join(str(x) for x in data[i:i+32]) + ',' for i in range(0,len(data),32))
    lines += ['};', '} // namespace Vulkan::KosIrisData', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    import sys
    content = bake()
    if '--check' in sys.argv:
        assert HEADER.read_text() == content, 'Embedded iris is stale; regenerate it.'
        print('Iris verified: 128x128, eight mip levels, 87380 bytes, aligned offsets.')
    else:
        HEADER.write_text(content)
        print(HEADER)
