"""Write src/core/vr/kos_lights_icon.h: Kos Lights' packet art for our VR card (our own art, drawn
by scripts/build_cigarette_patch.py's make_icon, BC7, PS4-tiled, 416 x 416), zlib-packed. The
emulator serves it as icon file 9000 (core/vr/bloodborne_kos_lights.cpp); the game's menus use its
own icon 343.
usage: python scripts/make_kos_icon_header.py STAGED_OR_INSTALLED/menu/menu_knowledge_09000.tpf.dcx"""
from pathlib import Path
import struct
import sys
import zlib

PAYLOAD = 13 * 13 * 64 * 16


def unpack_dcx(data):
    if data[:4] != b'DCX\0':
        raise ValueError('not a DCX')
    dcs = data.index(b'DCS\0')
    unpacked, packed = struct.unpack_from('>II', data, dcs + 4)
    dca = data.index(b'DCA\0')
    out = zlib.decompress(data[dca + 8:dca + 8 + packed])
    if len(out) != unpacked:
        raise ValueError('DCX size mismatch')
    return out


def main():
    tpf = unpack_dcx(Path(sys.argv[1]).read_bytes())
    if tpf[:4] != b'TPF\0' or struct.unpack_from('<I', tpf, 8)[0] != 1:
        raise ValueError('expected a one-texture TPF')
    offset, size = struct.unpack_from('<II', tpf, 16)
    if size != PAYLOAD:
        raise ValueError(f'unexpected payload size {size}')
    packed = zlib.compress(tpf[offset:offset + size], 9)
    lines = [', '.join(f'0x{b:02x}' for b in packed[i:i + 20]) for i in range(0, len(packed), 20)]
    out = Path(__file__).resolve().parents[1] / 'src/core/vr/kos_lights_icon.h'
    out.write_text(
        '// SPDX-FileCopyrightText: 2026 BB-VR contributors\n'
        '// SPDX-License-Identifier: GPL-2.0-or-later\n\n'
        '#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\n'
        '// Generated by scripts/make_kos_icon_header.py: Kos Lights\' packet for our VR card, our own\n'
        '// art (scripts/build_cigarette_patch.py make_icon), BC7, PS4 tile mode 13, 416 x 416 (400 x 400\n'
        '// used), zlib-packed. No game data.\n'
        'namespace VR::KosLights {\n'
        f'inline constexpr std::size_t IconUnpacked = {size};\n'
        f'inline constexpr std::uint8_t IconPacked[{len(packed)}] = {{\n'
        + ''.join(f'    {line},\n' for line in lines) +
        '};\n} // namespace VR::KosLights\n', encoding='utf-8', newline='\n')
    print(f'{out}: {size} bytes packed to {len(packed)}')


if __name__ == '__main__':
    main()
