bool Rasterizer::VrCapeSkip(const GraphicsPipeline* pipeline, u32 index_offset) {
    CapeState& cs = Cape();
    if (!cs.frame_checked) {
        cs.frame_checked = true;
        const bool first_person = FirstPersonFrame(cs);
        cs.frame_on = first_person && CapeEnabled(cs, Insp());
        VR::Holsters::Targets pouch{};
        cs.pouch_on = first_person && VR::GetSettings().inject &&
                      VR::Quick::GetQuickSettings().holster_mode != 0 &&
                      VR::Quick::GetQuickSettings().inframe &&
                      VR::Quick::LatestHolsterTargets(pouch) &&
                      VR::Holsters::Fresh(pouch, VR::Body::SteadyNowNs(),
                                          VR::DrawFrameRecord().space_serial) &&
                      pouch.layout.assignment[0] == 1;
        if (first_person && !cs.frame_on) {
            cs.reason = "hide_cape off";
        }
        // arms_only / hands_only: nothing of the body is left in the colour passes to cut away.
        const VR::Body::DrawnArms arms =
            first_person ? VR::Body::DrawnArmsNow() : VR::Body::DrawnArms::Whole;
        cs.hands_on = arms != VR::Body::DrawnArms::Whole;
        cs.hands_only = arms == VR::Body::DrawnArms::Hands;
        if (first_person && !cs.hands_on) {
            cs.cut_code = CutCode(cs);
            cs.shoulder_cut =
                VR::Tune::Get("body.cut_shoulders",
                              VR::Body::GetBodySettings().body_cutaway_shoulders ? 1.0f : 0.0f) >=
                0.5f;
            if (cs.cut_code != 0 && s32(cs.shoulder_cut) != cs.shoulder_logged &&
                cs.shoulder_log_budget != 0) {
                --cs.shoulder_log_budget;
                cs.shoulder_logged = s32(cs.shoulder_cut);
                LOG_INFO(Render_Vulkan, "VR cut: the upper arms and shoulders {}",
                         cs.shoulder_cut ? "fade with the body (body_cutaway_shoulders=1)"
                                         : "are kept with the arms (body_cutaway_shoulders=0)");
            }
        } else {
            cs.cut_code = 0;
            cs.cut_codes = {};
            cs.boost_level = 0;
        }
        if (cs.cut_code != 0) {
            ++cs.cut_frames;
            ++cs.boost_frames[std::min(cs.boost_level, 2u)];
        }
        // body_cutaway_boost: every change of its level (first 80).
        if (cs.cut_code != 0 && cs.boost_level != cs.boost_logged && cs.boost_log_budget != 0) {
            --cs.boost_log_budget;
            cs.boost_logged = cs.boost_level;
            if (cs.boost_level != 0) {
                LOG_INFO(Render_Vulkan,
                         "VR cut: boost {} ({}): the body fades out from {} to {} mm, its inside "
                         "never drawn",
                         cs.boost_level, VR::Body::CutBoost::WhyText(cs.boost.Why()),
                         (cs.cut_code >> 16) & 0x7FFFu, cs.cut_code & 0xFFFFu);
            } else {
                LOG_INFO(Render_Vulkan, "VR cut: boost off (the normal fade, {} to {} mm)",
                         (cs.cut_code >> 16) & 0x7FFFu, cs.cut_code & 0xFFFFu);
            }
        }
        cs.head_on = first_person && VR::Body::HeadHiddenByRenderer();
        cs.head_reason = first_person ? "head hidden by scaling or hands filter" : cs.reason;
        cs.hands_reason = first_person ? "body_mode not arms_only or hands_only" : cs.reason;
        // (A boost's changes have their own lines above.)
        if (cs.cut_code != cs.cut_logged_code && cs.boost_level == 0 && cs.cut_log_budget != 0) {
            --cs.cut_log_budget;
            cs.cut_logged_code = cs.cut_code;
            if (cs.cut_code != 0) {
                LOG_INFO(Render_Vulkan,
                         "VR cut: the hunter's body fades out from {} to {} mm from the camera{}",
                         (cs.cut_code >> 16) & 0x7FFFu, cs.cut_code & 0xFFFFu,
                         (cs.cut_code >> 31) != 0 ? ", its inside (back faces) never drawn" : "");
            } else {
                LOG_INFO(Render_Vulkan, "VR cut: off ({})",
                         !first_person ? cs.reason
                         : cs.hands_on ? "arms_only / hands_only: no coat drawn to fade"
                                       : "body_cutaway=0");
            }
        }
    }
    if (!cs.frame_on && cs.cut_code == 0 && !cs.head_on && !cs.hands_on && !cs.pouch_on) {
        return false;
    }
    // The main player: the model standing under the first-person camera (an NPC or another hunter
    // in the same armour would have to stand inside the player).
    VR::Vec3 object{};
    bool upright = false;
    if (!ObjectPosition(pipeline->GetStage(Shader::LogicalStage::Vertex), object, &upright)) {
        return false;
    }
    const float dx = (object.x - cs.camera.x) / cs.units_per_m;
    const float dz = (object.z - cs.camera.z) / cs.units_per_m;
    const float up = (cs.camera.y - object.y) / cs.units_per_m;
    if (cs.has_player) {
        // His skinned parts stand exactly at his origin, a hunter NPC next to him at its own; a
        // rigid piece on one of his bones (a bracer, a hat) is tilted and near him
        // (VrBodySplit::IsPlayersObject). arms_only / hands_only hide whole parts, so they must
        // never take someone else's.
        const float px = (object.x - cs.player.x) / cs.units_per_m;
        const float py = (object.y - cs.player.y) / cs.units_per_m;
        const float pz = (object.z - cs.player.z) / cs.units_per_m;
        bool his = VrBodySplit::IsPlayersObject(px, py, pz, upright);
        if (!his && upright && cs.others_next.size() < 128) {
            cs.others_next.push_back(object);
        }
        if (his && !upright) {
            // A piece within reach of him: someone else's when another root is nearer to it, or
            // when it was judged theirs a moment ago in the same place.
            const float mine = px * px + py * py + pz * pz;
            const auto& r = std::as_const(ScratchDraw::Registers(liverpool));
            const VAddr key = r.index_base_address.Address<VAddr>() +
                              VAddr(index_offset) *
                                  (r.index_buffer_type.index_type == AmdGpu::IndexType::Index16 ? 2
                                                                                                  : 4);
            auto& places = cs.theirs[key];
            const auto near_place = [&](const CapeState::Theirs& t) {
                const float ux = (object.x - t.at.x) / cs.units_per_m;
                const float uy = (object.y - t.at.y) / cs.units_per_m;
                const float uz = (object.z - t.at.z) / cs.units_per_m;
                return t.until >= cs.frame_no && ux * ux + uy * uy + uz * uz <= 0.25f;
            };
            const auto remember = [&] {
                CapeState::Theirs* slot = &places[0];
                for (auto& t : places) {
                    if (near_place(t) || t.until < slot->until) {
                        slot = &t;
                        if (near_place(t)) {
                            break;
                        }
                    }
                }
                *slot = {object, cs.frame_no + TheirsFrames};
            };
            for (const auto& t : places) {
                if (near_place(t)) {
                    his = false;
                    break;
                }
            }
            for (const auto& root : cs.others) {
                const float ox = (object.x - root.x) / cs.units_per_m;
                const float oy = (object.y - root.y) / cs.units_per_m;
                const float oz = (object.z - root.z) / cs.units_per_m;
                if (ox * ox + oy * oy + oz * oz < mine) {
                    his = false;
                    remember();
                    if (cs.others_log_budget != 0) {
                        --cs.others_log_budget;
                        LOG_INFO(Render_Vulkan,
                                 "VR hands: a piece {:.2f} m from his origin is {:.2f} m from "
                                 "another character's root: theirs, drawn as it is",
                                 std::sqrt(mine), std::sqrt(ox * ox + oy * oy + oz * oz));
                    }
                    break;
                }
            }
        }
        if (!his) {
            if (cs.hands_on && upright && dx * dx + dz * dz <= 1.0f && up >= 0.3f && up <= 2.6f) {
                ++cs.hands_missed;
                if (cs.missed_log_budget != 0) {
                    --cs.missed_log_budget;
                    LOG_INFO(Render_Vulkan,
                             "VR hands: a root under the camera {:.3f} m from his origin ({:.3f}, "
                             "{:.3f}, {:.3f}): not his, drawn as it is",
                             std::sqrt(px * px + py * py + pz * pz), px, py, pz);
                }
            }
            return false;
        }
        if (u32& budget = upright ? cs.player_log_budget : cs.piece_log_budget; budget != 0) {
            --budget;
            LOG_INFO(Render_Vulkan,
                     "VR hands: a draw of the hunter's model {:.3f} m from his origin ({:.3f}, "
                     "{:.3f}, {:.3f}; {})",
                     std::sqrt(px * px + py * py + pz * pz), px, py, pz,
                     upright ? "a root" : "a piece on a bone");
        }
    } else if (dx * dx + dz * dz > 1.0f || up < 0.3f || up > 2.6f) {
        return false; // the model standing under the camera
    }
    ++cs.player_draws;
    // A cape mesh: its index data is a cape face set of a parts file (vr_cape_table.h); a body
    // or leg face set (vr_body_table.h): what of it is cut away near the camera.
    const auto& regs = std::as_const(ScratchDraw::Registers(liverpool));
    const u32 index_size = regs.index_buffer_type.index_type == AmdGpu::IndexType::Index16 ? 2 : 4;
    const VAddr index_addr =
        regs.index_base_address.Address<VAddr>() + VAddr(index_offset) * index_size;
    const u32 count = regs.num_indices;
    const u64 bytes = u64(count) * index_size;
    if (count == 0 || bytes > (64u << 20) || index_addr < 0x10000) {
        return false;
    }
    const auto* data = reinterpret_cast<const u8*>(index_addr);
    const u64 check = EdgeHash(data, bytes);
    auto& entry = cs.by_index[index_addr];
    if (entry.count != count || entry.check != check) {
        // New here, or the memory now holds other index data: hash it whole (once).
        entry = {.count = count, .check = check};
        const u64 hash = Fnv1a(data, bytes);
        entry.hash = hash;
        entry.pouch_chain = FindKey(VrPouchTable::Keys, count, hash) != VrPouchTable::Keys.end();
        if (const auto ht = FindKey(VrHandsTable::Keys, count, hash);
            ht != VrHandsTable::Keys.end()) {
            entry.hands = static_cast<u32>(ht - VrHandsTable::Keys.begin()) + 1;
            if (cs.hands_on && cs.hands_log_budget != 0) {
                --cs.hands_log_budget;
                u32 hand = 0;
                u32 lower = 0;
                for (u32 r = 0; r < ht->hand; ++r) {
                    hand += VrHandsTable::Ranges[ht->begin + r].count;
                }
                for (u32 r = 0; r < ht->lower; ++r) {
                    lower += VrHandsTable::Ranges[ht->begin + ht->hand + r].count;
                }
                LOG_INFO(Render_Vulkan,
                         "VR hands: the player's face set {:#018x}: of {} indices {} are hand ({} ranges), {} hand "
                         "or forearm ({} ranges{}; at {:#x})",
                         hash, count, hand, ht->hand, lower, ht->lower,
                         ht->lower_all ? ", all of it" : "", index_addr);
            }
        }
        bool cape = false;
        if (const auto it = FindKey(VrCapeTable::Keys, count, hash);
            it != VrCapeTable::Keys.end()) {
            entry.kind = CapeKind::Whole;
            cape = true;
        } else if (const auto pt = FindKey(VrCapeTable::PartialKeys, count, hash);
                   pt != VrCapeTable::PartialKeys.end()) {
            entry.kind = CapeKind::Partial;
            entry.partial = static_cast<u32>(pt - VrCapeTable::PartialKeys.begin());
            cape = true;
        }
        if (const auto bt = FindKey(VrBodyTable::Keys, count, hash);
            bt != VrBodyTable::Keys.end()) {
            entry.body = static_cast<u32>(bt - VrBodyTable::Keys.begin()) + 1;
            if (bt->head_only || bt->head != 0) {
                if (cs.head_log_budget != 0) {
                    --cs.head_log_budget;
                    u32 head = 0;
                    const u32 head_at = bt->begin + bt->keep + bt->shoulder + bt->cut + bt->cape;
                    for (u32 r = 0; r < bt->head; ++r) {
                        head += VrBodyTable::Ranges[head_at + r].count;
                    }
                    LOG_INFO(Render_Vulkan,
                             "VR head: the player's face set {:#018x}: {} of {} indices are the head ({} ranges; "
                             "{}; at {:#x})",
                             hash, head, count, bt->head,
                             bt->head_only ? "a head part" : "a body face set", index_addr);
                }
            }
            if (!bt->head_only && cs.body_log_budget != 0) {
                --cs.body_log_budget;
                u32 shoulder = 0;
                u32 cut = 0;
                for (u32 r = 0; r < bt->shoulder; ++r) {
                    shoulder += VrBodyTable::Ranges[bt->begin + bt->keep + r].count;
                }
                for (u32 r = 0; r < u32(bt->cut) + bt->cape; ++r) {
                    cut += VrBodyTable::Ranges[bt->begin + bt->keep + bt->shoulder + r].count;
                }
                LOG_INFO(Render_Vulkan,
                         "VR cut: the player's face set {:#018x}: {} of {} indices fade out near the camera "
                         "({} ranges; {} arm ranges kept, {} cape ranges), and {} indices of the "
                         "upper arms and shoulders ({} ranges; at {:#x})",
                         hash, cut, count, bt->cut + bt->cape, bt->keep, bt->cape, shoulder,
                         bt->shoulder, index_addr);
            }
        }
        if (cape && cs.frame_on && cs.log_budget != 0) {
            --cs.log_budget;
            if (entry.kind == CapeKind::Whole) {
                LOG_INFO(Render_Vulkan, "VR cape: hiding the player's face set {:#018x} ({} indices at {:#x})",
                         hash, count, index_addr);
            } else {
                const auto& key = VrCapeTable::PartialKeys[entry.partial];
                u32 kept = 0;
                for (u32 r = 0; r < key.range_count; ++r) {
                    kept += VrCapeTable::Ranges[key.range_begin + r].count;
                }
                LOG_INFO(Render_Vulkan,
                         "VR cape: drawing the player's face set {:#018x} without its cape triangles ({} of {} "
                         "indices in {} ranges, at {:#x})",
                         hash, kept, count, key.range_count, index_addr);
            }
        }
    }
    if (cs.hands_on) {
        // arms_only / hands_only: in the camera's colour passes only the hands and forearms / the
        // hands of his parts (vr_hands_table.h); the shadow passes go on below (his whole body,
        // the cape rule).
        const float vp_w = regs.viewport_control.xscale_enable
                               ? 2.0f * std::abs(regs.viewports[0].xscale)
                               : 0.0f;
        const float vp_h = regs.viewport_control.yscale_enable
                               ? 2.0f * std::abs(regs.viewports[0].yscale)
                               : 0.0f;
        const bool colour = VrBodySplit::HeadHiddenPass(pipeline->GetGraphicsKey().mrt_mask != 0,
                                                        vp_w, vp_h, VR::MainAspect());
        if (!colour && entry.hands != 0) {
            ++cs.hands_shadow; // the shadow maps: his whole body (it casts its full shadow)
        }
        if (colour) {
            // The fixture's three rigid near-player candidates are explicitly allowlisted.
            // Their identity must be checked in the depth dumps; proximity alone is insufficient.
            producer_vr.probe_selected = entry.hands != 0 || entry.hash == 0x7db78a0c91f10546ULL ||
                                         entry.hash == 0x0184f2888f6684c2ULL ||
                                         entry.hash == 0xe881fd8fe40cb35dULL;
            if (entry.hands == 0) {
                // All hand (a bare hand), or not one of his parts: drawn as it is.
                ++cs.hands_other;
                if (!entry.other_logged && cs.other_log_budget != 0) {
                    entry.other_logged = true;
                    --cs.other_log_budget;
                    LOG_INFO(Render_Vulkan,
                             "VR hands: drawn as it is near the camera: {} indices, hash {:#018x} "
                             "at {:#x}, object {:.2f} m right / {:.2f} m below / {:.2f} m ahead "
                             "(world axes) of the camera, vs {:#x}",
                             count, entry.hash, index_addr, dx, up, dz,
                             pipeline->GetGraphicsKey()
                                 .stage_hashes[u32(Shader::LogicalStage::Vertex)]);
                }
                return false;
            }
            const auto& hk = VrHandsTable::Keys[entry.hands - 1];
            const u32 ranges = cs.hands_only ? hk.hand : hk.lower;
            switch (VrBodySplit::PlanHands(
                true, true, ranges, !cs.hands_only && hk.lower_all,
                regs.primitive_type == AmdGpu::PrimitiveType::TriangleList)) {
            case VrBodySplit::HandsAction::Skip:
                ++cs.hands_skipped;
                return true;
            case VrBodySplit::HandsAction::Hands:
                cs.hands_split = &VrHandsTable::Ranges[hk.begin + (cs.hands_only ? 0 : hk.hand)];
                cs.hands_split_count = ranges;
                ++cs.hands_drawn;
                return false;
            case VrBodySplit::HandsAction::Untouched:
                return false;
            }
        }
    }
    if (entry.pouch_chain && cs.pouch_on) {
        return true;
    }
    if (entry.kind == CapeKind::Whole && cs.frame_on) {
        ++cs.skipped;
        return true;
    }
    if (entry.body != 0) {
        // The body cutaway: a face set without arms (and without hidden cape triangles) is cut
        // whole (VrCutPipeline gives it the cutaway pipeline); otherwise VrDrawCapeSplit draws
        // its arm ranges with the draw's own pipeline and its other ranges with the cutaway one.
        // body_head_shadow: in a colour pass the head's triangles are left out (a head part
        // whole), in the shadow (depth-only) passes they are drawn (VrBodySplit::PlanDraw).
        const auto& key = VrBodyTable::Keys[entry.body - 1];
        const u32 mrt = pipeline->GetGraphicsKey().mrt_mask;
        const float vp_w = regs.viewport_control.xscale_enable
                               ? 2.0f * std::abs(regs.viewports[0].xscale)
                               : 0.0f;
        const float vp_h = regs.viewport_control.yscale_enable
                               ? 2.0f * std::abs(regs.viewports[0].yscale)
                               : 0.0f;
        const bool colour =
            VrBodySplit::HeadHiddenPass(mrt != 0, vp_w, vp_h, VR::MainAspect());
        if (cs.head_on && key.head != 0 && cs.pass_log_budget != 0) {
            // Each kind of pass the head's face sets are drawn in (first 12): which ones leave
            // the head out.
            const u64 pass_key = (u64(mrt) << 40) ^ (u64(vp_w) << 20) ^ u64(vp_h);
            if (std::find(cs.passes_logged.begin(), cs.passes_logged.end(), pass_key) ==
                cs.passes_logged.end()) {
                cs.passes_logged.push_back(pass_key);
                --cs.pass_log_budget;
                LOG_INFO(Render_Vulkan,
                         "VR head: a pass of {:.0f}x{:.0f} (colour targets {:#x}, frame aspect "
                         "{:.3f}): the head {}",
                         vp_w, vp_h, mrt, VR::MainAspect(),
                         colour ? "left out" : "drawn (casts its shadow)");
            }
        }
        const VrBodySplit::KeyShape shape{key.keep, key.cut,       key.cape,
                                          key.head, key.head_only, key.shoulder};
        const bool triangles = regs.primitive_type == AmdGpu::PrimitiveType::TriangleList;
        const VrBodySplit::Plan plan = VrBodySplit::PlanDraw(
            shape, {cs.cut_code != 0, cs.frame_on, cs.head_on, cs.shoulder_cut}, colour,
            triangles);
        if (cs.head_on && key.head != 0 && !colour) {
            ++cs.head_shadow;
        }
        // The cutaway configured but not cutting this frame (looking ahead): would it cut this
        // draw (VrCutPipeline then prebuilds its variant)?
        if (cs.cut_code == 0 && colour && cs.cut_codes[0] != 0 &&
            VrBodySplit::PlanDraw(shape, {true, cs.frame_on, cs.head_on, cs.shoulder_cut}, colour,
                                  triangles)
                .cut) {
            cs.cut_ahead = cs.cut_codes[0];
        }
        switch (plan.action) {
        case VrBodySplit::Action::Skip:
            ++cs.head_skipped;
            return true;
        case VrBodySplit::Action::Split:
            cs.body_split = &key;
            cs.body_cape_hidden = !plan.draw_cape;
            cs.body_head_hidden = !plan.draw_head;
            cs.body_shoulder_cut = plan.cut_shoulder;
            if (key.cape != 0 && !plan.draw_cape) {
                ++cs.split_draws;
            }
            if (!plan.draw_head) {
                ++cs.head_split;
            }
            [[fallthrough]];
        case VrBodySplit::Action::Whole:
            // Only the camera's own passes (HeadHiddenPass): a shadow map with colour targets
            // (the point lights') keeps the whole body and needs no cutaway pipeline.
            cs.cut_request = plan.cut && colour ? cs.cut_code : 0;
            return false;
        case VrBodySplit::Action::Untouched:
            break;
        }
    }
    if (!cs.frame_on) {
        return false;
    }
    switch (entry.kind) {
    case CapeKind::Whole:
        ++cs.skipped;
        return true;
    case CapeKind::Partial:
        if (regs.primitive_type != AmdGpu::PrimitiveType::TriangleList) {
            return false; // the ranges are triangles of a list
        }
        cs.split = &VrCapeTable::Ranges[VrCapeTable::PartialKeys[entry.partial].range_begin];
        cs.split_count = VrCapeTable::PartialKeys[entry.partial].range_count;
        ++cs.split_draws;
        return false;
    case CapeKind::None:
        break;
    }
    return false;
}

bool Rasterizer::VrDrawCapeSplit(RecorderProxy cmdbuf, u32 instances, s32 vertex_offset,
                                 u32 instance_offset) {
    auto& cs = recording_vr;
    if (const VrHandsTable::Range* hands = cs.hands_split; hands != nullptr) {
        // arms_only / hands_only: only the kept triangles, with the draw's own pipeline.
        const u32 n = cs.hands_split_count;
        cs.hands_split = nullptr;
        cs.hands_split_count = 0;
        for (u32 r = 0; r < n; ++r) {
            cmdbuf.drawIndexed(hands[r].count, instances, hands[r].first, vertex_offset,
                               instance_offset);
        }
        return true;
    }
    if (const VrBodyTable::Key* key = cs.body_split; key != nullptr) {
        // A body face set with arms: the arms with the draw's pipeline (bound), then the rest
        // with the cutaway pipeline (the same layout: only the fragment shader differs). Without
        // a cutaway pipeline (shadow passes) everything but the hidden cape triangles. The
        // shoulder ranges (the upper arms) go with the cut ones (body_cutaway_shoulders) or with
        // the arms; they follow the keep ranges, so either way two runs of ranges.
        const GraphicsPipeline* cut_pipeline = cs.body_cut_pipeline;
        const bool cape_hidden = cs.body_cape_hidden;
        const bool head_hidden = cs.body_head_hidden;
        const bool shoulder_cut = cs.body_shoulder_cut && cut_pipeline != nullptr;
        cs.body_split = nullptr;
        cs.body_cut_pipeline = nullptr;
        cs.body_head_hidden = false;
        cs.body_shoulder_cut = false;
        if (cut_pipeline == nullptr && (!cape_hidden || key->cape == 0) &&
            (!head_hidden || key->head == 0)) {
            return false; // nothing left out, one pipeline (a shadow pass): the draw as it is
        }
        const VrBodyTable::Range* r = &VrBodyTable::Ranges[key->begin];
        const auto draw = [&](u32 first, u32 n) {
            for (u32 k = first; k < first + n; ++k) {
                cmdbuf.drawIndexed(r[k].count, instances, r[k].first, vertex_offset,
                                   instance_offset);
            }
        };
        const u32 kept = u32(key->keep) + (shoulder_cut ? 0u : key->shoulder);
        const u32 cut_at = u32(key->keep) + key->shoulder;
        draw(0, kept);
        if (cut_pipeline != nullptr) {
            cmdbuf.bindPipeline(vk::PipelineBindPoint::eGraphics, cut_pipeline->Handle());
        }
        draw(kept, cut_at + key->cut - kept);
        if (!cape_hidden) {
            draw(cut_at + key->cut, key->cape);
        }
        if (!head_hidden) {
            draw(cut_at + key->cut + key->cape, key->head);
        }
        return true;
    }
    const VrCapeTable::Range* ranges = cs.split;
    const u32 count = cs.split_count;
    cs.split = nullptr;
    cs.split_count = 0;
    if (ranges == nullptr) {
        return false;
    }
    for (u32 r = 0; r < count; ++r) {
        cmdbuf.drawIndexed(ranges[r].count, instances, ranges[r].first, vertex_offset,
                           instance_offset);
    }
    return true;
}

bool Rasterizer::PrepareVrDraw(const GraphicsPipeline*& pipeline, bool indexed, bool indirect,
                               u32 offset) {
    producer_vr = {};
    if (!vr_warp)
        return true;
    if (VrFilterDraw(pipeline, indexed, indirect, offset))
        return false;
    const u32 cut = Cape().cut_request;
    pipeline = VrCutPipeline(pipeline);
    const auto& cs = Cape();
    producer_vr.split = cs.split;
    producer_vr.split_count = cs.split_count;
    producer_vr.body_split = cs.body_split;
    producer_vr.body_cut_pipeline = cs.body_cut_pipeline;
    producer_vr.body_cape_hidden = cs.body_cape_hidden;
    producer_vr.body_head_hidden = cs.body_head_hidden;
    producer_vr.body_shoulder_cut = cs.body_shoulder_cut;
    producer_vr.hands_split = cs.hands_split;
    producer_vr.hands_split_count = cs.hands_split_count;
    producer_vr.cut_code = cut;
    return true;
}

const GraphicsPipeline* Rasterizer::ReselectVrCut(const GraphicsPipeline* pipeline) {
    if (!recording_vr.cut_code || !pipeline->GetGraphicsKey().mrt_mask)
        return pipeline;
    // Bit 40: null while the cut variant of the reselected pipeline compiles (never waited for).
    const auto* cut = pipeline_cache.GetVrCutPipeline(pipeline, recording_vr.cut_code, false);
    if (recording_vr.body_split) {
        // Null: the cut ranges go uncut, never with Stage A's cut pipeline of the other view mask.
        recording_vr.body_cut_pipeline = cut;
        return pipeline;
    }
    return cut ? cut : pipeline;
}

const GraphicsPipeline* Rasterizer::VrCutPipeline(const GraphicsPipeline* pipeline) {
    CapeState& cs = Cape();
    const u32 cut = cs.cut_request;
    const u32 ahead = cs.cut_ahead;
    cs.cut_request = 0;
    cs.cut_ahead = 0;
    cs.body_cut_pipeline = nullptr;
    // Only colour passes from the camera (the G-buffer): the shadow cascades and other
    // depth-only passes keep the whole body (an invisible coat would cast no shadow).
    if (cut == 0 || pipeline == nullptr || pipeline->GetGraphicsKey().mrt_mask == 0) {
        // Fast bit 40 with VrPushData: the body's one cut variant compiles in the background
        // from its first colour draw, before the cutaway first asks for it.
        if (cut == 0 && ahead != 0 && pipeline != nullptr &&
            pipeline->GetGraphicsKey().mrt_mask != 0 && pipeline_cache.UsesVrPushData() &&
            FastRender::On(AsyncPipelinesBit)) {
            pipeline_cache.PrebuildVrCutPipeline(pipeline, ahead, true);
        }
        return pipeline;
    }
    // Bit 40: null while it compiles in the background; the body is drawn uncut meanwhile (and
    // VrDrawCapeSplit draws its cut ranges with the draw's own pipeline).
    const GraphicsPipeline* cut_pipeline = pipeline_cache.GetVrCutPipeline(pipeline, cut, false);
    if (cut_pipeline == nullptr) {
        return pipeline;
    }
    // The other cuts this body pipeline may need (body_cutaway_boost's levels, the pitch steps),
    // built now with this draw's registers: a first hit or head drop never waits for a compile.
    // Each is built once (a map lookup after that). Fast bit 40: their pipelines compile in the
    // background (their shader permutations still here); GetVrCutPipeline installs them.
    // VrPushData: there are no others (every cut is this variant, the draw pushes its radii).
    if (!pipeline_cache.UsesVrPushData()) {
        const bool background = FastRender::On(AsyncPipelinesBit);
        for (const u32 other : cs.cut_codes) {
            if (other != 0 && other != cut) {
                if (background)
                    pipeline_cache.PrebuildVrCutPipeline(pipeline, other);
                else
                    pipeline_cache.GetVrCutPipeline(pipeline, other);
            }
        }
    }
    ++cs.cut_draws;
    if (cs.body_split != nullptr) {
        cs.body_cut_pipeline = cut_pipeline; // VrDrawCapeSplit binds it for the cut ranges
        return pipeline;
    }
    return cut_pipeline;
}

bool Rasterizer::VrIsComposite(const GraphicsPipeline* pipeline) {
    const u64 frame = FastRender::g_counters.frames.load(std::memory_order_relaxed);
    if (frame != vr_skip_hud_frame) {
        vr_skip_hud_frame = frame;
        vr_skip_hud_vs = VR::GetSettings().hud_after_vs;
    }
    return pipeline->GuestShaderKey(Shader::LogicalStage::Vertex) == vr_skip_hud_vs;
}

PipelineSkip::Veto Rasterizer::VrSkipVeto(const Shader::Info* vs) {
    using PipelineSkip::Veto;
    // Only an immersive frame (PipelineSkip::ImmersiveFrame): the camera record of this draw
    // (Draw's own on Stage A).
    const VR::CameraRecord rec = VR::DrawFrameRecord();
    const PipelineSkip::FrameState frame{
        .vr = vr_warp != nullptr,
        .immersive = VR::IsImmersive(),
        .cinematic_flat = VR::CinematicFlat(),
        .driven = rec.driven,
        .has_camera = rec.has_render_position,
        .menu = rec.menu,
        .first_person = rec.first_person,
        .has_player = rec.has_player_position,
    };
    if (!PipelineSkip::ImmersiveFrame(frame)) {
        return Veto::Frame;
    }
    // After the composite: the HUD and menus (Scaleform's stencil marks), drawn into the eyes.
    // Without a composite in the frame before, the UI phase cannot be told: nothing is left out.
    const u64 now = FastRender::g_counters.frames.load(std::memory_order_relaxed);
    const auto phase = PipelineSkip::Phase(vr_skip_ui_frame, now);
    if (phase == PipelineSkip::UiPhase::Unknown) {
        // Once a session: candidates for 600 frames and still no composite (hud_after_vs not
        // this game's composite?).
        if (vr_skip_ui_missing == ~u64{0}) {
            vr_skip_ui_missing = now;
        } else if (!vr_skip_ui_logged && now - vr_skip_ui_missing > 600) {
            vr_skip_ui_logged = true;
            LOG_WARNING(Render_Vulkan,
                        "FAST async_pipelines skip: no composite (hud_after_vs {:#x}) drawn for "
                        "600 frames of gameplay: skip-the-draw leaves nothing out until one is",
                        vr_skip_hud_vs);
        }
        return Veto::Ui;
    }
    vr_skip_ui_missing = ~u64{0};
    if (phase == PipelineSkip::UiPhase::Ui) {
        return Veto::Ui;
    }
    // The hunter's own draws by their object transform, as VrCapeSkip finds them (a draw without
    // one cannot be told his, here as there).
    VR::Vec3 object{};
    bool upright = false;
    if (vs == nullptr || !ObjectPosition(*vs, object, &upright)) {
        return Veto::None;
    }
    const float units = rec.world_scale > 0.0f ? rec.world_scale : 1.0f;
    const PipelineSkip::Offset to_player{(object.x - rec.player_position.x) / units,
                                         (object.y - rec.player_position.y) / units,
                                         (object.z - rec.player_position.z) / units};
    const PipelineSkip::Offset to_camera{(object.x - rec.render_position.x) / units,
                                         (object.y - rec.render_position.y) / units,
                                         (object.z - rec.render_position.z) / units};
    return PipelineSkip::PlayersDraw(rec.first_person, rec.has_player_position, to_player, upright,
                                     to_camera)
               ? Veto::Player
               : Veto::None;
}

bool Rasterizer::VrFilterDraw(const GraphicsPipeline* pipeline, bool is_indexed, bool indirect,
                              u32 index_offset) {
    producer_vr.probe_selected = false;
    Cape().split = nullptr;       // set again below for a partial cape face set
    Cape().cut_request = 0;       // set again below for the hunter's body
    Cape().cut_ahead = 0;         // ... or for his body while the cutaway is not cutting
    Cape().body_split = nullptr;  // set again below for a body face set with arms
    Cape().body_head_hidden = false;
    Cape().body_shoulder_cut = false;
    Cape().hands_split = nullptr; // set again below for a hunter face set with hand triangles
    const bool cape = is_indexed && !indirect && VrCapeSkip(pipeline, index_offset);
    // AA image replacement and its outcome counters belong to recording.
    const bool aa_skip = false;
    Inspector& insp = Insp();
    if (!insp.enabled) {
        return cape || aa_skip;
    }
    const auto& regs = std::as_const(ScratchDraw::Registers(liverpool));
    DrawInfo d{};
    d.index = insp.index++;
    const auto& key = pipeline->GetGraphicsKey();
    d.vs = key.stage_hashes[u32(Shader::LogicalStage::Vertex)];
    d.fs = key.stage_hashes[u32(Shader::LogicalStage::Fragment)];
    d.indexed = is_indexed;
    d.indirect = indirect;
    d.n = indirect ? 0 : regs.num_indices;
    d.instances = regs.num_instances.NumInstances();
    if (is_indexed) {
        const bool is16 = regs.index_buffer_type.index_type == AmdGpu::IndexType::Index16;
        d.ib = regs.index_base_address.Address<VAddr>() + index_offset * (is16 ? 2 : 4);
        d.ib_size = is16 ? 16 : 32;
    }
    if (regs.color_buffers[0]) {
        d.cb = regs.color_buffers[0].Address();
    }
    d.db = regs.depth_buffer.DepthAddress();

    const bool want_detail = insp.log_frames != 0 || insp.dump_armed || !insp.skip.empty();
    if (want_detail) {
        VertexInputs<vk::VertexInputAttributeDescription2EXT> attributes;
        VertexInputs<vk::VertexInputBindingDescription2EXT> bindings;
        VertexInputs<vk::VertexInputBindingDivisorDescriptionEXT> divisors;
        VertexInputs<AmdGpu::Buffer> guest_buffers;
        pipeline->GetVertexInputs(attributes, bindings, divisors, guest_buffers,
                                  regs.vgt_instance_step_rate_0, regs.vgt_instance_step_rate_1);
        for (const auto& b : guest_buffers) {
            d.vbs.push_back({b.base_address, static_cast<u32>(b.GetSize()), b.GetStride()});
        }
        for (const auto* stage : pipeline->GetStages()) {
            if (stage == nullptr) {
                continue;
            }
            if (stage->l_stage == Shader::LogicalStage::Vertex) {
                CollectBuffers(*stage, d.vs_bufs);
            } else if (stage->l_stage == Shader::LogicalStage::Fragment) {
                CollectBuffers(*stage, d.fs_bufs);
                for (const auto& image : stage->images) {
                    const auto t = image.GetSharp(*stage);
                    d.textures.push_back(
                        {t.Address(), static_cast<u32>(t.width + 1), static_cast<u32>(t.height + 1),
                         static_cast<u32>(t.data_format), static_cast<u32>(t.num_format)});
                }
            }
        }
    }

    bool skip = cape || aa_skip;
    for (const auto& m : insp.skip) {
        if (Matches(m, d)) {
            skip = true;
            break;
        }
    }
    if (skip) {
        ++insp.skipped;
    }
    if (insp.log_frames != 0) {
        std::string tex = "[";
        for (const auto& t : d.textures) {
            if (tex.size() > 1) {
                tex += ',';
            }
            tex += fmt::format("{:#x}:{}x{}:{}/{}", t.addr, t.width, t.height, t.dfmt, t.nfmt);
        }
        tex += ']';
        const auto& blend = key.blend_controls[0];
        LOG_INFO(Render_Vulkan,
                 "VRDRAWX f={} i={} skip={} vs={:#x} fs={:#x} n={} inst={} ind={} ib={:#x}/{} "
                 "prim={} cb={:#x} db={:#x} dw={} blend={} cull={} vb={} vsb={} fsb={} tex={}{}",
                 insp.frame, d.index, skip ? 1 : 0, d.vs, d.fs, d.n, d.instances,
                 indirect ? 2 : (is_indexed ? 1 : 0), d.ib, d.ib_size,
                 static_cast<u32>(regs.primitive_type), d.cb, d.db,
                 regs.depth_control.depth_write_enable ? 1 : 0, blend.enable != 0 ? 1 : 0,
                 static_cast<u32>(regs.polygon_control.cull_front) |
                     (static_cast<u32>(regs.polygon_control.cull_back) << 1),
                 BufList(d.vbs, true), BufList(d.vs_bufs, false), BufList(d.fs_bufs, false), tex,
                 aa_skip ? " aa=skip"
                 : false ? " aa=taa"
                         : (false ? " aa=smaa" : ""));
        ++insp.logged;
    }
    if (insp.dump_armed) {
        for (const auto& m : insp.dump) {
            if (!Matches(m, d)) {
                continue;
            }
            LOG_INFO(Render_Vulkan, "VR draws: dumping frame {} draw {} (vs {:#x} n {})",
                     insp.frame, d.index, d.vs, d.n);
            for (size_t k = 0; k < d.vs_bufs.size(); ++k) {
                DumpBuffer(insp, d, "vsb", k, d.vs_bufs[k]);
            }
            for (size_t k = 0; k < d.fs_bufs.size(); ++k) {
                DumpBuffer(insp, d, "fsb", k, d.fs_bufs[k]);
            }
            for (size_t k = 0; k < d.vbs.size(); ++k) {
                DumpBuffer(insp, d, "vb", k, d.vbs[k]);
            }
            if (d.ib != 0 && d.n != 0) {
                DumpBuffer(insp, d, "ib", 0, {d.ib, d.n * (d.ib_size / 8), d.ib_size / 8});
            }
            break;
        }
    }
    return skip;
}

void Rasterizer::VrDrawsEndFrame() {
    CapeState& cs = Cape();
    cs.others.swap(cs.others_next);
    cs.others_next.clear();
    if (++cs.frame_no % 256 == 0) {
        std::erase_if(cs.theirs, [&](const auto& entry) {
            return std::ranges::all_of(entry.second,
                                       [&](const auto& t) { return t.until < cs.frame_no; });
        });
    }
    if (cs.frame_checked) {
        cs.cut_total += cs.cut_draws;
        if (cs.frame_on) {
            ++cs.frames_on;
            cs.skipped_total += cs.skipped;
            cs.split_total += cs.split_draws;
            if (cs.player_draws == 0) {
                ++cs.window_no_player;
            } else {
                cs.window_min = std::min(cs.window_min, cs.skipped + cs.split_draws);
                cs.window_max = std::max(cs.window_max, cs.skipped + cs.split_draws);
            }
        }
        // Every switch between hidden and shown (first 40).
        const bool shown = !cs.frame_on;
        if ((!cs.any_logged || shown != cs.shown_logged) && cs.switch_budget != 0) {
            --cs.switch_budget;
            cs.any_logged = true;
            cs.shown_logged = shown;
            if (shown) {
                LOG_INFO(Render_Vulkan, "VR cape: shown ({})", cs.reason);
            } else {
                LOG_INFO(Render_Vulkan, "VR cape: hidden (first-person VR)");
            }
        }
        if (cs.frame_on && cs.frames_on % 600 == 0) {
            LOG_INFO(Render_Vulkan,
                     "VR cape: last 600 first-person frames: {} cape draws left out, {} drawn "
                     "without their cape triangles, {} .. {} a frame, {} frames without the "
                     "player (this frame: {} + {} of the player's {} draws; {} index buffers "
                     "known); body cutaway: {} draws ({} this frame), {} frames: {} normal, {} "
                     "boost 1, {} boost 2",
                     cs.skipped_total, cs.split_total, cs.window_min == ~0u ? 0 : cs.window_min,
                     cs.window_max, cs.window_no_player, cs.skipped, cs.split_draws,
                     cs.player_draws, cs.by_index.size(), cs.cut_total, cs.cut_draws,
                     cs.cut_frames, cs.boost_frames[0], cs.boost_frames[1], cs.boost_frames[2]);
            cs.cut_total = 0;
            cs.cut_frames = 0;
            cs.boost_frames[0] = cs.boost_frames[1] = cs.boost_frames[2] = 0;
            cs.skipped_total = 0;
            cs.split_total = 0;
            cs.window_min = ~0u;
            cs.window_max = 0;
            cs.window_no_player = 0;
        }
        // body_head_shadow: every switch (first 40) and the 600-frame line.
        if ((!cs.head_any_logged || cs.head_on != cs.head_logged_on) &&
            cs.head_switch_budget != 0 && (cs.head_on || cs.head_any_logged)) {
            --cs.head_switch_budget;
            cs.head_any_logged = true;
            cs.head_logged_on = cs.head_on;
            if (cs.head_on) {
                LOG_INFO(Render_Vulkan, "VR head: left out of the colour passes, drawn in the "
                                        "shadows (body_head_shadow, first-person VR)");
            } else {
                LOG_INFO(Render_Vulkan, "VR head: drawn ({})",
                         cs.head_reason);
            }
        }
        // arms_only / hands_only: every switch (first 40) and the 600-frame line.
        if ((!cs.hands_any_logged || cs.hands_on != cs.hands_logged_on ||
             cs.hands_only != cs.hands_logged_only) &&
            cs.hands_switch_budget != 0 && (cs.hands_on || cs.hands_any_logged)) {
            --cs.hands_switch_budget;
            cs.hands_any_logged = true;
            cs.hands_logged_on = cs.hands_on;
            cs.hands_logged_only = cs.hands_only;
            if (cs.hands_on) {
                LOG_INFO(Render_Vulkan,
                         "VR hands: only the hunter's {} in the colour passes, his whole body in "
                         "the shadows (body_mode={}, first-person VR)",
                         cs.hands_only ? "hands" : "hands and forearms",
                         cs.hands_only ? "hands_only" : "arms_only");
            } else {
                LOG_INFO(Render_Vulkan, "VR hands: the whole hunter drawn ({})", cs.hands_reason);
            }
        }
        if (cs.hands_on) {
            cs.hands_skipped_total += cs.hands_skipped;
            cs.hands_drawn_total += cs.hands_drawn;
            cs.hands_other_total += cs.hands_other;
            cs.hands_shadow_total += cs.hands_shadow;
            cs.hands_missed_total += cs.hands_missed;
            if (++cs.hands_frames % 600 == 0) {
                LOG_INFO(Render_Vulkan,
                         "VR hands: last 600 first-person frames: {} colour draws of his parts "
                         "left out, {} drawn as their hands, {} other draws near the camera, {} "
                         "draws of his parts in the shadow passes, {} roots under the camera not "
                         "at his origin (this frame: {} / {} / {} / {} / {})",
                         cs.hands_skipped_total, cs.hands_drawn_total, cs.hands_other_total,
                         cs.hands_shadow_total, cs.hands_missed_total, cs.hands_skipped,
                         cs.hands_drawn, cs.hands_other, cs.hands_shadow, cs.hands_missed);
                cs.hands_skipped_total = 0;
                cs.hands_drawn_total = 0;
                cs.hands_other_total = 0;
                cs.hands_shadow_total = 0;
                cs.hands_missed_total = 0;
            }
        }
        if (cs.head_on) {
            cs.head_skipped_total += cs.head_skipped;
            cs.head_split_total += cs.head_split;
            cs.head_shadow_total += cs.head_shadow;
            if (++cs.head_frames % 600 == 0) {
                LOG_INFO(Render_Vulkan,
                         "VR head: last 600 first-person frames: {} head-part colour draws left "
                         "out, {} drawn without their head triangles, {} shadow draws of the head "
                         "(this frame: {} + {}, {} shadow)",
                         cs.head_skipped_total, cs.head_split_total, cs.head_shadow_total,
                         cs.head_skipped, cs.head_split, cs.head_shadow);
                cs.head_skipped_total = 0;
                cs.head_split_total = 0;
                cs.head_shadow_total = 0;
            }
        }
    }
    cs.frame_checked = false;
    cs.hands_skipped = 0;
    cs.hands_drawn = 0;
    cs.hands_other = 0;
    cs.hands_shadow = 0;
    cs.hands_missed = 0;
    cs.hands_split = nullptr;
    cs.hands_split_count = 0;
    cs.head_skipped = 0;
    cs.head_split = 0;
    cs.head_shadow = 0;
    cs.body_head_hidden = false;
    cs.skipped = 0;
    cs.split_draws = 0;
    cs.player_draws = 0;
    cs.cut_draws = 0;
    cs.cut_request = 0;
    cs.body_split = nullptr;
    cs.body_cut_pipeline = nullptr;
    cs.split = nullptr;
    Inspector& insp = Insp();
    if (!insp.enabled) {
        return;
    }
    for (const auto& [addr, len] : insp.mem) {
        DumpMemory(insp, memory, addr, len);
    }
    insp.mem.clear();
    for (const auto& f : insp.find) {
        FindFloats(memory, f);
    }
    insp.find.clear();
    WatchPoll();
    for (const auto& [key, value] : insp.settings) {
        // As the VR page does: the vr.ini parser, live (not saved to vr.ini).
        const bool ok = VR::ApplySetting(key, value);
        LOG_INFO(Render_Vulkan, "VR draws: set {}={} {}", key, value, ok ? "applied" : "refused");
    }
    insp.settings.clear();
    for (const auto& [addr, len] : insp.gpumem) {
        buffer_cache.RequestReadback(addr, len);
        insp.mem_later.emplace_back(insp.frame + 8, addr, len);
    }
    insp.gpumem.clear();
    std::erase_if(insp.mem_later, [&](const auto& later) {
        const auto& [frame, addr, len] = later;
        if (insp.frame < frame) {
            return false;
        }
        DumpMemory(insp, memory, addr, len);
        return true;
    });
    if (insp.log_frames != 0) {
        LOG_INFO(Render_Vulkan, "VRDRAWX end f={} draws={} skipped={}", insp.frame, insp.index,
                 insp.skipped);
        --insp.log_frames;
    }
    insp.dump_armed = false;
    ++insp.frame;
    insp.index = 0;
    insp.skipped = 0;
    Poll(insp);
    if (insp.log_request != 0) {
        insp.log_frames = insp.log_request;
        insp.log_request = 0;
    }
    if (insp.dump_request) {
        insp.dump_armed = true;
        insp.dump_request = false;
    }
}

// The inspector's `log` also lists the compute dispatches, in the draws' order (VRDISPX: the
// index they share with the draws, the program, its buffers and images; 'w' = written). A table
// a pass reads that the GPU fills (guest memory all zeros with readbacks off) is found by its
// writer here.
// True: `skipcs` drops this dispatch (logged as skip=1).
bool Rasterizer::VrLogDispatch(const ComputePipeline* pipeline, bool indirect) {
    Inspector& insp = Insp();
    if (!insp.enabled) {
        return false;
    }
    const auto& cs = pipeline->GetStage(Shader::LogicalStage::Compute);
    const bool skip = std::find(insp.skip_cs.begin(), insp.skip_cs.end(), cs.pgm_hash) !=
                      insp.skip_cs.end();
    if (insp.log_frames == 0) {
        return skip;
    }
    std::string bufs = "[";
    for (const auto& desc : cs.buffers) {
        if (desc.IsSpecial()) {
            continue;
        }
        const auto sharp = desc.GetSharp(cs);
        if (bufs.size() > 1) {
            bufs += ',';
        }
        bufs += fmt::format("{:#x}:{}{}", sharp.base_address, sharp.GetSize(),
                            desc.is_written ? "w" : "");
    }
    bufs += ']';
    std::string images = "[";
    for (const auto& image : cs.images) {
        const auto t = image.GetSharp(cs);
        if (images.size() > 1) {
            images += ',';
        }
        images += fmt::format("{:#x}:{}x{}{}", t.Address(), t.width + 1, t.height + 1,
                              image.is_written ? "w" : "");
    }
    images += ']';
    LOG_INFO(Render_Vulkan, "VRDISPX f={} i={} skip={} cs={:#x} ind={} bufs={} img={}",
             insp.frame, insp.index++, skip ? 1 : 0, cs.pgm_hash, indirect ? 1 : 0, bufs, images);
    return skip;
}

