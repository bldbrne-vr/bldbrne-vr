// VR draw inspector (debug, GPU thread): finds and filters individual game draws.
//
// VR_DRAW_CTL=<file>: the file is re-read whenever it changes (polled at most every 200 ms, at
// the flips). One command per line, '#' starts a comment:
//   log <N>              the next N frames' draws are logged (VRDRAWX lines: draw index in the
//                        frame, shader hashes, index and vertex buffers, the shaders' buffers and
//                        textures, colour and depth targets); one-shot per change of the file
//   skip <matcher>       every matching draw is dropped (until the file changes again)
//   skipcs <hash>        every dispatch of that compute program is dropped (likewise)
//   find <f0> <f1> <f2>  logs (VRFIND) the guest addresses where these three floats follow each
//                        other (each within 0.002), in every readable mapping; one-shot
//   watch <addr> <len> [n]  the next n (default 8) CPU writes to those pages are logged (VRWATCH:
//                        the guest code address and return-address candidates from the stack);
//                        only for memory the GPU does not track (a heap array, not a GPU buffer)
//   dump <matcher>       the next frame's matching draws dump their vertex and pixel shader
//                        buffers (and vertex buffers) to <file dir>/dump_f<frame>_i<index>_*.bin
//   mem <addr> <len>     dumps guest memory (within its mapping) to <file dir>/mem_<addr>.bin
//   set <key> <value>    a vr.ini setting applied live, as the VR page does (not saved)
//   gpumem <addr> <len>  the same for memory the GPU wrote: copied back first (at the frame's
//                        end), dumped 8 frames later
//   cape <0|1>           turns the cape filter (below) off / on for this run
// A matcher is a list of key=value terms, all of which must match: vs=<hash> fs=<hash> n=<index
// count> ib=<index buffer address> vb=<any vertex buffer address> buf=<any shader buffer address>
// tex=<any texture address> cb=<colour target address> idx=<a>-<b> (the draw's index in the frame).
// Numbers are decimal or 0x hex.
//
// Cape filter (vr.ini hide_cape=1, the default; VR_HIDE_CAPE=0|1 or `cape 0|1` above override it):
// in first-person VR frames (gameplay and the frozen view behind the menu panel) the main player's
// cape is not drawn, in every pass (the G-buffer and the four shadow cascades); flat cinematics,
// the virtual screen, the game's own cameras (title, loading, cutscenes, character creation) and
// third person draw it as usual. Nothing in the game is changed (no memory, param or save write),
// so there is nothing to restore: the next frame that is not first person draws the cape again.
// Bloodborne loads a model's (FLVER) data section verbatim into GPU memory, so a draw's index data
// is byte for byte one face set of a parts file. vr_cape_table.h (generated by
// an offline generator, not included) lists
// - every face set of the meshes whose material or default bone is named cape / mantle / cloak
//   (e.g. BD_M_8000's cloth cape and collar flap): such a draw is left out;
// - face sets of meshes the cape shares with the shirt (Foreign Garb 'body': the capelet's
//   shoulder band, its chain and clasps) with the index ranges without those triangles: such a
//   draw is recorded as several draws of the kept ranges (VrDrawCapeSplit);
// keyed by index count and FNV-1a of the index bytes; no other mesh of any parts file has the
// same index data. The draw is the main player's when its object transform (the 416-byte vertex
// shader constant buffer: a 3x4 world matrix first) stands under the first-person camera
// (horizontally within 1 m, the camera 0.3 .. 2.6 m above it). Each index buffer is hashed once;
// its first and last 32 bytes are re-checked on every use (memory is reused when models unload).
// While the VR body runs, the frame's camera record also carries the hunter's model origin
// (CameraRecord::player_position): a draw is his when its object transform stands there, or is a
// rigid piece on one of his bones near him (VrBodySplit::IsPlayersObject).
//
// body_mode=arms_only / hands_only (VR::Body::DrawnArmsNow): in the camera's colour passes of
// those frames only the hand and forearm / the hand triangles of his parts are drawn
// (vr_hands_table.h, generated offline: every face set of his
// am_/bd_/lg_/hd_/fc_/fg_/hr_ parts that is not all hand, with its hand ranges and its hand-and-
// forearm ranges); everything else at his origin is drawn as it is, his weapons, the gun, the
// vial and items are other models (never his), and the shadow passes keep his whole body.
// Nothing is scaled, so nothing is torn.

