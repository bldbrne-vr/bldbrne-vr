CapeState& Cape() {
    static CapeState state = [] {
        CapeState c{};
        if (const char* value = std::getenv("VR_HIDE_CAPE"); value != nullptr && *value != '\0') {
            c.env = *value == '0' ? 0 : 1;
            LOG_INFO(Render_Vulkan, "VR cape: VR_HIDE_CAPE={} overrides vr.ini hide_cape", c.env);
        }
        return c;
    }();
    return state;
}

u64 Fnv1a(const u8* data, size_t size, u64 h = 0xCBF29CE484222325ull) {
    for (size_t i = 0; i < size; ++i) {
        h = (h ^ data[i]) * 0x100000001B3ull;
    }
    return h;
}

// The cheap per-use check of an index buffer: its first and last 32 bytes.
u64 EdgeHash(const u8* data, u64 bytes) {
    const u64 edge = std::min<u64>(bytes, 32);
    return Fnv1a(data + bytes - edge, edge, Fnv1a(data, edge));
}

template <typename Table>
auto FindKey(const Table& keys, u32 count, u64 hash) {
    const auto it = std::lower_bound(keys.begin(), keys.end(), std::pair{count, hash},
                                     [](const auto& a, const std::pair<u32, u64>& b) {
                                         return a.count != b.first ? a.count < b.first
                                                                   : a.hash < b.second;
                                     });
    return it != keys.end() && it->count == count && it->hash == hash ? it : keys.end();
}

// The draw's object transform: the first 416-byte vertex shader constant buffer whose first three
// rows are a rotation with a translation (Bloodborne's per-object constants; the same buffer in
// the G-buffer and the shadow passes). False when the draw has none. `upright`: its up axis is the
// world's (a character root; a rigid piece on a bone is tilted).
bool ObjectPosition(const Shader::Info& vs, VR::Vec3& out, bool* upright = nullptr) {
    for (const auto& desc : vs.buffers) {
        if (desc.IsSpecial()) {
            continue;
        }
        const auto sharp = desc.GetSharp(vs);
        if (sharp.GetSize() != 416 || sharp.base_address < 0x10000) {
            continue;
        }
        float m[12];
        std::memcpy(
            m,
            ScratchDraw::MemorySource(reinterpret_cast<const void*>(sharp.base_address), sizeof(m)),
            sizeof(m));
        bool ok = true;
        for (int r = 0; r < 3 && ok; ++r) {
            const float n =
                m[r * 4] * m[r * 4] + m[r * 4 + 1] * m[r * 4 + 1] + m[r * 4 + 2] * m[r * 4 + 2];
            ok = std::isfinite(n) && n > 0.6f && n < 1.6f && std::isfinite(m[r * 4 + 3]);
        }
        if (ok) {
            out = {m[3], m[7], m[11]};
            if (upright != nullptr) {
                *upright = m[5] > 0.9995f;
            }
            return true;
        }
    }
    return false;
}

// Once per frame: is this a first-person VR frame (the camera placed by the headset in the
// hunter's head), and if not, why (for the switch lines).
bool FirstPersonFrame(CapeState& cs) {
    if (!VR::IsFirstPerson()) {
        cs.boost.CancelLadder(VR::Body::SteadyNowNs());
        cs.reason = "third person";
        return false;
    }
    if (VR::GetDisplayMode() != VR::DisplayMode::Auto) {
        cs.boost.CancelLadder(VR::Body::SteadyNowNs());
        cs.reason = "virtual screen";
        return false;
    }
    if (VR::CinematicFlat()) {
        cs.boost.CancelLadder(VR::Body::SteadyNowNs());
        cs.reason = "cinematic";
        return false;
    }
    // A remo cutscene: the game's camera looks at the hunter (his head, cape and body drawn),
    // though the frames reuse the last first-person camera record (2026-10-15).
    if (VR::RemoCutscenePlaying()) {
        cs.boost.CancelLadder(VR::Body::SteadyNowNs());
        cs.reason = "cutscene";
        return false;
    }
    // The frame's camera was placed by the headset in the hunter's head (gameplay, and the frozen
    // view behind the menu panel); the title, loading, cutscenes, the character creation and the
    // virtual screen show the game's own cameras.
    const VR::CameraRecord rec = VR::DrawFrameRecord();
    if (!rec.driven || !rec.has_render_position) {
        // Missing camera data only skips this frame; it is not a switch to a flat screen.
        cs.reason = "game camera";
        return false;
    }
    cs.camera = rec.render_position;
    cs.units_per_m = rec.world_scale > 0.0f ? rec.world_scale : 1.0f;
    cs.has_player = rec.has_player_position;
    cs.player = rec.player_position;
    cs.reason = "";
    return true;
}

bool CapeEnabled(const CapeState& cs, const Inspector& insp) {
    return insp.cape_override >= 0 ? insp.cape_override == 1
           : cs.env >= 0           ? cs.env == 1
                                   : VR::Body::GetBodySettings().hide_cape;
}

// A cutaway as FragmentRuntimeInfo::vr_cut: near and far in millimetres of game units, bit 31 =
// back faces cut; 0 = none.
u32 EncodeCut(const CapeState& cs, float near_m, float far_m, bool inside) {
    const auto mm = [&](float m) {
        return static_cast<u32>(std::clamp(m * cs.units_per_m * 1000.0f, 0.0f, 65535.0f) + 0.5f);
    };
    const u32 near_mm = std::min(mm(near_m), 32766u);
    const u32 far_mm = std::min(std::max(mm(std::max(far_m, near_m)), near_mm + 1), 32767u);
    return far_mm <= 1 ? 0 : (near_mm | (far_mm << 16) | (inside ? 0u : 0x80000000u));
}

// body_cutaway_boost: this frame's level from the newest body status (core/vr/body_cut_boost.h).
// VR_TUNE_FILE body.cut_boost / body.cut_boost_behind_m / body.cut_boost_below_m /
// body.cut_boost_hold_s: live A/B.
u32 CutBoostLevel(CapeState& cs) {
    const auto& bs = VR::Body::GetBodySettings();
    if (VR::Tune::Get("body.cut_boost", bs.body_cutaway_boost ? 1.0f : 0.0f) < 0.5f) {
        return 0;
    }
    const s64 now = VR::Body::SteadyNowNs();
    VR::Body::CutBoostInput in{};
    in.ladder_start_ns = VR::Bloodborne::LatestLadderStartNs();
    VR::Body::BodyStatus status{};
    if (VR::Body::LatestBodyStatus(status) && status.driven &&
        now - status.steady_ns < 250'000'000) {
        in.fresh = true;
        in.hit = status.look_only || status.stun_clip >= 0 || status.daze != 0;
        in.cam_ahead_m = status.cam_ahead_m;
        in.cam_above_m = status.cam_above_m;
        in.cam_side_m = status.cam_side_m;
    }
    VR::Body::CutBoostParams params{};
    if (bs.body_comfort) {
        params.side_m = 0.055f;
        params.recovery_s = 0.2f;
    }
    params.behind_m = VR::Tune::Get("body.cut_boost_behind_m", params.behind_m);
    params.below_m = VR::Tune::Get("body.cut_boost_below_m", params.below_m);
    params.hold_s = VR::Tune::Get("body.cut_boost_hold_s", params.hold_s);
    const u32 level = cs.boost.Update(in, now, params);
    // body.cut_boost_force=0|1|2: that level whatever the body does (side-by-side tests only).
    const float force = VR::Tune::Get("body.cut_boost_force", -1.0f);
    return force >= 0.0f ? std::min(static_cast<u32>(force + 0.5f), 2u) : level;
}

// This first-person frame's cutaway (EncodeCut), 0 = off. VR_TUNE_FILE body.cut /
// body.cut_near_m / body.cut_far_m / body.cut_back / body.cut_boost_near_m / body.cut_boost_far_m:
// live A/B. Also fills cs.cut_codes with every cut a body pipeline may need.
u32 CutCode(CapeState& cs) {
    const auto& bs = VR::Body::GetBodySettings();
    cs.cut_codes = {};
    cs.boost_level = 0;
    if (VR::Tune::Get("body.cut", bs.body_cutaway ? 1.0f : 0.0f) < 0.5f) {
        return 0;
    }
    const VR::Body::CutRadii base{
        VR::Tune::Get("body.cut_near_m", bs.body_cutaway_near_m),
        VR::Tune::Get("body.cut_far_m", bs.body_cutaway_far_m),
        VR::Tune::Get("body.cut_back", bs.body_cutaway_inside ? 0.0f : 1.0f) <= 0.5f};
    const float boost_near = VR::Tune::Get("body.cut_boost_near_m", bs.body_cutaway_boost_near_m);
    const float boost_far = VR::Tune::Get("body.cut_boost_far_m", bs.body_cutaway_boost_far_m);
    const u32 boost = CutBoostLevel(cs);
    cs.boost_level = boost;
    const auto boosted = [&](u32 level) {
        const VR::Body::CutRadii r = VR::Body::BoostedRadii(base, boost_near, boost_far, level);
        return EncodeCut(cs, r.near_m, r.far_m, r.inside);
    };
    if (VR::Tune::Get("body.cut_boost", bs.body_cutaway_boost ? 1.0f : 0.0f) >= 0.5f) {
        cs.cut_codes[2] = boosted(1);
        cs.cut_codes[3] = boosted(2);
    }
    // Only when looking down far enough to see the chest (body_cutaway_pitch_deg, 0 = always):
    // looking ahead or a little down the body stays whole; half the radius from that pitch, the
    // full one 15 degrees further down (three steps, so only three pipeline variants).
    float scale = 1.0f;
    const float start_deg = VR::Tune::Get("body.cut_pitch_deg", bs.body_cutaway_pitch_deg);
    if (start_deg > 0.0f) {
        const VR::CameraRecord rec = VR::DrawFrameRecord();
        // Your head's own pitch (render_pitch_bias_deg: the record's is the render camera's).
        const float down = -rec.TrueHeadPitch() * (180.0f / 3.14159265f);
        constexpr float Hyst = 2.0f;
        const float half_at = start_deg;
        const float full_at = start_deg + 15.0f;
        u32 level = cs.cut_level;
        if (level == 0 && down > half_at + Hyst) {
            level = 1;
        }
        if (level >= 1 && down > full_at + Hyst) {
            level = 2;
        }
        if (level == 2 && down < full_at - Hyst) {
            level = 1;
        }
        if (level >= 1 && down < half_at - Hyst) {
            level = 0;
        }
        cs.cut_level = level;
        cs.cut_codes[1] = EncodeCut(cs, 0.5f * base.near_m, 0.5f * base.far_m, base.inside);
        scale = level == 0 ? 0.0f : level == 1 ? 0.5f : 1.0f;
    }
    cs.cut_codes[0] = EncodeCut(cs, base.near_m, base.far_m, base.inside);
    // A boost applies at any pitch (the camera inside his collar while looking ahead too).
    if (boost != 0) {
        return boosted(boost);
    }
    if (scale == 0.0f) {
        return 0;
    }
    return EncodeCut(cs, scale * base.near_m, scale * base.far_m, base.inside);
}

